const STORAGE_KEY = 'grid-games-language-v1';
let currentLanguage = 'fr';

export function getLanguage() {
  try {
    const savedLanguage = localStorage.getItem(STORAGE_KEY);
    currentLanguage = Object.hasOwn(LANGUAGES, savedLanguage)
      ? savedLanguage
      : 'fr';
  } catch (error) {
    console.error('Impossible de lire la langue enregistrée.', error);
    currentLanguage = 'fr';
  }
  return currentLanguage;
}

export function setLanguage(language) {
  if (!Object.hasOwn(LANGUAGES, language)) {
    throw new RangeError(`Unsupported language: ${language}`);
  }
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch (error) {
    console.error('Impossible d’enregistrer la langue choisie.', error);
    throw error;
  }
  currentLanguage = language;
}

export function getLanguageOptions() {
  return Object.entries(LANGUAGES).map(([code, language]) => ({
    code,
    ...language,
  }));
}

export function getCurrentLanguage() {
  return currentLanguage;
}

export function translate(key, values = {}) {
  const template =
    translations[currentLanguage]?.[key] ?? translations.fr[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    String(values[name] ?? `{${name}}`),
  );
}

export function getCurrentLocale() {
  return LANGUAGES[currentLanguage].locale;
}

export function getGameName(game) {
  if (game === 'patches') return 'Patches';
  if (game === 'zip') return 'Zip';
  if (game === 'queens') return 'Queens';
  return 'Tango';
}
